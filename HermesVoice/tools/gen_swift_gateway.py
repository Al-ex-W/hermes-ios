#!/usr/bin/env python3
"""Render the pinned Hermes gateway contract (OpenRPC) into Swift for HermesVoice.

Stdlib only. Mirrors the deliberately small JSON-Schema-subset renderer in Hermes'
``scripts/gen_gateway_contracts.py``: a construct outside that subset raises, so a contract change is
handled here instead of being papered over in the output.

    python3 HermesVoice/tools/gen_swift_gateway.py           # regenerate Gateway/Generated/
    python3 HermesVoice/tools/gen_swift_gateway.py --check   # exit 1 when Generated/ is stale
    python3 HermesVoice/tools/gen_swift_gateway.py --update  # re-pin the contract from Hermes, then regenerate

Mapping: ``anyOf[T, null]`` or not required -> ``T?``; a multi-type ``anyOf`` -> an enum that tries each
type; ``oneOf`` + discriminator -> an enum with one case per mapping tag; ``additionalProperties: true``
beside properties -> ``extras: [String: JSONValue]``; schema-valued ``additionalProperties`` ->
``[String: T]``; opaque -> ``JSONValue``; string enums keep unknown values in ``unknown(String)``.
Encoders omit nil members (params are ``extra="forbid"`` and many fields reject null); a member that is
required but nullable is written as an explicit null.
"""

