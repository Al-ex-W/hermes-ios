# ── Naming ────────────────────────────────────────────────────────────────────────────────────────


def _words(text: str) -> list[str]:
    return [w for w in re.split(r"[^A-Za-z0-9]+", text) if w]


def _upper_first(text: str) -> str:
    return text[:1].upper() + text[1:]


def _lower_first(text: str) -> str:
    return text[:1].lower() + text[1:]


def lower_camel(text: str) -> str:
    """``session_id`` -> ``sessionId``, ``deny-all`` -> ``denyAll``, ``NOT_OWNER`` -> ``notOwner``."""
    words = [w.lower() if w.isupper() else w for w in _words(text)]
    if not words:
        return "value"
    out = _lower_first(words[0]) + "".join(_upper_first(w) for w in words[1:])
    return "_" + out if out[0].isdigit() else out


def upper_camel(text: str) -> str:
    words = [w.lower() if w.isupper() and len(w) > 1 else w for w in _words(text)]
    out = "".join(_upper_first(w) for w in words) or "Value"
    return "_" + out if out[0].isdigit() else out


def camel_words(name: str) -> list[str]:
    return re.findall(r"[A-Z]+(?![a-z])|[A-Z][a-z0-9]*|[a-z0-9]+", name)


def ident(name: str) -> str:
    """A bare name as a Swift identifier (backticks for keywords)."""
    return f"`{name}`" if name in SWIFT_KEYWORDS else name


def unique(name: str, taken: set[str]) -> str:
    if name in UNESCAPABLE:
        name += "_"
    candidate, n = name, 2
    while candidate in taken:
        candidate, n = f"{name}{n}", n + 1
    taken.add(candidate)
    return candidate


def swift_string(value: str) -> str:
    out = []
    for ch in value:
        if ch in '"\\':
            out.append("\\" + ch)
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\r":
            out.append("\\r")
        elif ch == "\t":
            out.append("\\t")
        elif ord(ch) < 0x20:
            out.append(f"\\u{{{ord(ch):x}}}")
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def swift_literal(value) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, str):
        return swift_string(value)
    if isinstance(value, (int, float)):
        return repr(value)
    raise UnsupportedSchema(f"unsupported const literal: {value!r}")


def doc(text: str | None, indent: str = "", width: int = 110) -> str:
    """One ``///`` block: whitespace collapsed, RST ````code```` turned into Markdown ```code```."""
    if not text:
        return ""
    clean = re.sub(r"``(.+?)``", r"`\1`", " ".join(text.split()))
    lines = textwrap.wrap(clean, width=max(40, width - len(indent) - 4), break_long_words=False,
                          break_on_hyphens=False)
    return "".join(f"{indent}/// {line}\n" for line in lines)


# ── Type model ────────────────────────────────────────────────────────────────────────────────────


@dataclass(frozen=True)
class SwiftType:
    kind: str  # "prim" | "named" | "json" | "array" | "map"
    name: str = ""
    inner: "SwiftType | None" = None
    inner_optional: bool = False

    @property
    def swift(self) -> str:
        if self.kind in ("prim", "named"):
            return self.name
        if self.kind == "json":
            return "JSONValue"
        inner = self.inner.swift + ("?" if self.inner_optional else "")
        return f"[{inner}]" if self.kind == "array" else f"[String: {inner}]"

    @property
    def label(self) -> str:
        """The case name this type gets inside a multi-type enum."""
        if self.kind == "prim":
            return self.name.lower()
        if self.kind == "json":
            return "json"
        if self.kind == "named":
            return _lower_first(self.name)
        if self.kind == "map":
            return self.inner.label + "Map"
        depth, base = 1, self.inner
        while base.kind == "array":
            depth, base = depth + 1, base.inner
        return base.label + ("Array" if depth == 1 else f"Array{depth}D")


JSON_TYPE = SwiftType("json")


def prim(name: str) -> SwiftType:
    return SwiftType("prim", name)


@dataclass
class Field:
    wire: str
    name: str  # bare Swift name
    type: SwiftType
    optional: bool
    explicit_null: bool  # required but nullable: encoded as null instead of omitted
    default: str | None  # Swift literal for a required const
    doc: str | None

    @property
    def decl_type(self) -> str:
        return self.type.swift + ("?" if self.optional else "")


@dataclass
class StructInfo:
    name: str
    fields: list[Field]
    extras: SwiftType | None  # value type of `extras`, when the schema is open
    extras_optional: bool

    @property
    def zero_arg_init(self) -> bool:
        return all(f.optional or f.default is not None for f in self.fields)


# ── Contract ──────────────────────────────────────────────────────────────────────────────────────


@dataclass
class Call:
    name: str
    summary: str
    params: dict
    result: dict | None


def _refs(node) -> set[str]:
    found: set[str] = set()
    if isinstance(node, dict):
        for key, value in node.items():
            if key == "$ref" and isinstance(value, str):
                found.add(value.rsplit("/", 1)[-1])
            else:
                found |= _refs(value)
    elif isinstance(node, list):
        for value in node:
            found |= _refs(value)
    return found


def _closure(roots: set[str], schemas: dict) -> set[str]:
    seen, todo = set(), list(roots)
    while todo:
        name = todo.pop()
        if name in seen:
            continue
        if name not in schemas:
            raise UnsupportedSchema(f"dangling $ref: {name}")
        seen.add(name)
        todo.extend(_refs(schemas[name]) - seen)
    return seen


def is_stripped_method(name: str) -> bool:
    return name.startswith(STRIP_METHOD_PREFIXES)


def is_stripped_event(name: str) -> bool:
    return name.startswith(STRIP_EVENT_PREFIXES) or name in STRIP_EVENTS


class Contract:
    def __init__(self, doc: dict):
        self.schemas: dict[str, dict] = doc.get("components", {}).get("schemas", {})

        def calls(entries):
            out = []
            for entry in entries:
                params = entry.get("params") or []
                if len(params) != 1:
                    raise UnsupportedSchema(f"{entry['name']}: expected exactly one params object")
                result = entry.get("result")
                out.append(Call(entry["name"], entry.get("summary", ""), params[0]["schema"],
                                result["schema"] if result else None))
            return sorted(out, key=lambda c: c.name)

        all_methods = calls(doc.get("methods", []))
        all_requests = calls(doc.get("x-server-requests", []))
        all_events = calls(doc.get("x-notifications", []))
        self.methods = [m for m in all_methods if not is_stripped_method(m.name)]
        self.stripped_methods = [m for m in all_methods if is_stripped_method(m.name)]
        self.requests = all_requests
        self.events = [e for e in all_events if not is_stripped_event(e.name)]
        self.stripped_events = [e for e in all_events if is_stripped_event(e.name)]

        def roots(entries):
            return set().union(*[_refs(c.params) | _refs(c.result) for c in entries]) if entries else set()

        kept = _closure(roots(self.methods) | roots(self.requests) | roots(self.events), self.schemas)
        stripped = _closure(roots(self.stripped_methods) | roots(self.stripped_events), self.schemas)
        self.stripped_schemas = sorted(stripped - kept)
        self.kept_schemas = sorted(set(self.schemas) - set(self.stripped_schemas))


# ── Rendering ─────────────────────────────────────────────────────────────────────────────────────


class Renderer:
    def __init__(self, contract: Contract):
        self.contract = contract
        self.schemas = contract.schemas
        self.type_names: dict[str, str] = {}
        taken: set[str] = set()
        for name in sorted(self.schemas):
            swift = ("Gateway" + name) if name in RESERVED_TYPES else name
            if swift in taken:
                raise UnsupportedSchema(f"schema name collision after renaming: {name}")
            taken.add(swift)
            self.type_names[name] = swift
        self.all_names = set(self.type_names.values()) | RESERVED_TYPES
        self.structs: dict[str, StructInfo] = {}
        self.synth: dict[str, str] = {}  # synthesized type name -> source
        self.synth_keys: dict[tuple, str] = {}
        self.owner = ""  # schema being rendered (names unions by their first user)

    # Types ------------------------------------------------------------------------------------------

    def resolve(self, schema: dict, ctx: str) -> tuple[SwiftType, bool]:
        """The Swift type of ``schema`` and whether it is nullable. ``ctx`` names inline types."""
        unknown = set(schema) - IGNORED_KEYWORDS - STRUCTURAL_KEYWORDS
        if unknown:
            raise UnsupportedSchema(f"{ctx}: unsupported JSON-Schema keywords {sorted(unknown)}")
        if "$ref" in schema:
            name = schema["$ref"].rsplit("/", 1)[-1]
            if name not in self.type_names:
                raise UnsupportedSchema(f"{ctx}: dangling $ref {name}")
            return SwiftType("named", self.type_names[name]), False
        if "anyOf" in schema:
            return self.any_of(schema["anyOf"], ctx)
        if "oneOf" in schema:
            if "discriminator" not in schema:
                raise UnsupportedSchema(f"{ctx}: oneOf without a discriminator")
            return self.tagged_union(schema, ctx), False
        if "const" in schema:
            return self.const_type(schema, ctx), False
        if "enum" in schema:
            return self.inline_enum(schema, ctx), False
        kind = schema.get("type")
        if isinstance(kind, list):
            return self.any_of([{**schema, "type": k} for k in kind], ctx)
        if kind in PRIMITIVES:
            return prim(PRIMITIVES[kind]), False
        if kind == "null":
            return JSON_TYPE, True
        if kind == "array":
            items = schema.get("items")
            if items is None:
                return SwiftType("array", inner=JSON_TYPE), False
            inner, nullable = self.resolve(items, ctx + "Item")
            return SwiftType("array", inner=inner, inner_optional=nullable), False
        if kind == "object" or "properties" in schema or "additionalProperties" in schema:
            if schema.get("properties"):
                name = self.synth_name(("struct", ctx), ctx)
                if name not in self.synth:
                    self.synth[name] = ""
                    self.synth[name] = self.struct_source(name, schema)
                return SwiftType("named", name), False
            extra = schema.get("additionalProperties")
            if isinstance(extra, dict):
                inner, nullable = self.resolve(extra, ctx + "Value")
                return SwiftType("map", inner=inner, inner_optional=nullable), False
            return SwiftType("map", inner=JSON_TYPE), False
        if not set(schema) - IGNORED_KEYWORDS:
            return JSON_TYPE, False
        raise UnsupportedSchema(f"{ctx}: unsupported JSON-Schema construct {json.dumps(schema)[:200]}")

    @staticmethod
    def is_null(schema: dict) -> bool:
        return schema.get("type") == "null" and not set(schema) - IGNORED_KEYWORDS - {"type"}

    @staticmethod
    def is_opaque(schema: dict) -> bool:
        return not set(schema) - IGNORED_KEYWORDS

    def any_of(self, variants: list[dict], ctx: str) -> tuple[SwiftType, bool]:
        non_null = [v for v in variants if not self.is_null(v)]
        nullable = len(non_null) != len(variants)
        if not non_null:
            return JSON_TYPE, True
        if any(self.is_opaque(v) for v in non_null):
            return JSON_TYPE, nullable
        resolved = list(OrderedDict.fromkeys(self.resolve(v, ctx)[0] for v in non_null))
        if len(resolved) == 1:
            return resolved[0], nullable
        return self.choice_enum(resolved), nullable

    def const_type(self, schema: dict, ctx: str) -> SwiftType:
        kind = schema.get("type")
        if kind in PRIMITIVES:
            return prim(PRIMITIVES[kind])
        value = schema["const"]
        for py, swift in ((bool, "Bool"), (str, "String"), (int, "Int"), (float, "Double")):
            if isinstance(value, py):
                return prim(swift)
        raise UnsupportedSchema(f"{ctx}: unsupported const {value!r}")

    def synth_name(self, key: tuple, preferred: str) -> str:
        if key in self.synth_keys:
            return self.synth_keys[key]
        if preferred in self.all_names:
            raise UnsupportedSchema(f"generated type name {preferred} collides with a schema or reserved name")
        self.all_names.add(preferred)
        self.synth_keys[key] = preferred
        return preferred

    def inline_enum(self, schema: dict, ctx: str) -> SwiftType:
        name = self.synth_name(("enum", ctx), ctx)
        if name not in self.synth:
            self.synth[name] = self.enum_source(name, schema)
        return SwiftType("named", name)

    def choice_enum(self, variants: list[SwiftType]) -> SwiftType:
        ordered = sorted(variants, key=lambda t: VARIANT_RANK.get(t.swift, len(VARIANT_RANK)))
        key = ("choice", tuple(t.swift for t in ordered))
        if key in self.synth_keys:
            return SwiftType("named", self.synth_keys[key])
        name = self.synth_name(key, "Or".join(_upper_first(t.label) for t in ordered))
        self.synth[name] = self.choice_source(name, ordered)
        return SwiftType("named", name)

    def tagged_union(self, schema: dict, ctx: str) -> SwiftType:
        disc = schema["discriminator"]
        prop, mapping = disc["propertyName"], disc.get("mapping") or {}
        if not mapping:
            raise UnsupportedSchema(f"{ctx}: discriminator without a mapping")
        tags = [(tag, ref.rsplit("/", 1)[-1]) for tag, ref in mapping.items()]
        for _, target in tags:
            if target not in self.type_names:
                raise UnsupportedSchema(f"{ctx}: discriminator maps to unknown schema {target}")
        key = ("union", prop, tuple(tags))
        if key in self.synth_keys:
            return SwiftType("named", self.synth_keys[key])
        members = list(OrderedDict.fromkeys(self.type_names[t] for _, t in tags))
        name = self.synth_name(key, self.union_name(members))
        self.synth[name] = self.union_source(name, prop, [(tag, self.type_names[t]) for tag, t in tags])
        return SwiftType("named", name)

    def union_name(self, members: list[str]) -> str:
        """Shared words of the member names (``WaitBarrierUntil`` + ``WaitBarrierTarget`` -> ``WaitBarrier``);
        a one-word result is qualified with the first user's leading words (``Owner`` -> ``ConnectionOwner``)."""
        split = [camel_words(m) for m in members]
        prefix: list[str] = []
        for words in zip(*split):
            if len(set(words)) != 1:
                break
            prefix.append(words[0])
        shortest = min(len(w) for w in split)
        suffix: list[str] = []
        for i in range(1, shortest - len(prefix) + 1):
            words = {w[-i] for w in split}
            if len(words) != 1:
                break
            suffix.insert(0, words.pop())
        base = prefix + suffix
        name = "".join(base)
        if len(base) >= 2 and name not in self.all_names:
            return name
        owner_words = camel_words(self.owner)
        for n in range(1, len(owner_words) + 1):
            candidate = "".join(owner_words[:n] + base)
            if (len(owner_words[:n] + base) >= 2 and candidate not in self.all_names):
                return candidate
        return name + "Union"

    # Sources ----------------------------------------------------------------------------------------

    def schema_source(self, name: str) -> str:
        schema = self.schemas[name]
        swift = self.type_names[name]
        self.owner = swift
        description = schema.get("description")
        if "enum" in schema and "properties" not in schema:
            return self.enum_source(swift, schema, description)
        if schema.get("type") == "object" or "properties" in schema:
            extra = schema.get("additionalProperties")
            if not schema.get("properties") and isinstance(extra, dict):
                return doc(description) + f"typealias {swift} = {self.resolve(schema, swift)[0].swift}\n"
            return self.struct_source(swift, schema, description)
        resolved, nullable = self.resolve(schema, swift)
        return doc(description) + f"typealias {swift} = {resolved.swift}{'?' if nullable else ''}\n"

    def struct_source(self, name: str, schema: dict, description: str | None = None) -> str:
        props = schema.get("properties") or {}
        required = set(schema.get("required") or ())
        extra = schema.get("additionalProperties")
        taken = {"hashValue", "CodingKeys"}
        extras_type, extras_optional = None, False
        if extra is True:
            extras_type = JSON_TYPE
        elif isinstance(extra, dict):
            extras_type, extras_optional = self.resolve(extra, name + "Value")
        if extras_type is not None:
            taken.add("extras")
        fields = []
        for wire, sub in props.items():
            resolved, nullable = self.resolve(sub, name + upper_camel(wire))
            is_required = wire in required
            default = None
            if "const" in sub and is_required and not nullable:
                default = swift_literal(sub["const"])
            fields.append(Field(wire=wire, name=unique(lower_camel(wire), taken), type=resolved,
                                optional=nullable or not is_required, explicit_null=is_required and nullable,
                                default=default, doc=sub.get("description")))
        info = StructInfo(name, fields, extras_type, extras_optional)
        self.structs[name] = info

        custom = extras_type is not None or any(f.explicit_null for f in fields)
        renamed = any(f.name != f.wire for f in fields)
        out = [doc(description), f"struct {name}: Codable, Hashable, Sendable {{\n"]
        for f in fields:
            out.append(doc(f.doc, "    "))
            default = f" = {f.default}" if f.default is not None else ""
            out.append(f"    var {ident(f.name)}: {f.decl_type}{default}\n")
        if extras_type is not None:
            value = extras_type.swift + ("?" if extras_optional else "")
            out.append("    /// Members outside the contract, kept as sent.\n")
            out.append(f"    var extras: [String: {value}] = [:]\n")
        if fields and (custom or renamed):
            conformances = "String, CodingKey, CaseIterable" if extras_type is not None else "String, CodingKey"
            out.append(f"\n    enum CodingKeys: {conformances} {{\n")
            for f in fields:
                raw = f" = {swift_string(f.wire)}" if f.name != f.wire else ""
                out.append(f"        case {ident(f.name)}{raw}\n")
            out.append("    }\n")
        out.append("}\n")
        if custom:
            out.append(self.custom_codable(info))
        return "".join(out)

    def custom_codable(self, info: StructInfo) -> str:
        known = "Set(CodingKeys.allCases.map(\\.stringValue))" if info.fields else "[]"
        out = [f"\nextension {info.name} {{\n", "    init(from decoder: Decoder) throws {\n"]
        if info.fields:
            out.append("        let container = try decoder.container(keyedBy: CodingKeys.self)\n")
        for f in info.fields:
            method = "decodeIfPresent" if f.optional else "decode"
            out.append(f"        self.{ident(f.name)} = try container.{method}({f.type.swift}.self, "
                       f"forKey: .{ident(f.name)})\n")
        if info.extras is not None:
            value = info.extras.swift + ("?" if info.extras_optional else "")
            type_arg = "" if value == "JSONValue" else f"{value}.self, "
            out.append(f"        self.extras = try decoder.extraValues({type_arg}excluding: {known})\n")
        out.append("    }\n\n    func encode(to encoder: Encoder) throws {\n")
        if info.fields:
            out.append("        var container = encoder.container(keyedBy: CodingKeys.self)\n")
        for f in info.fields:
            method = "encodeIfPresent" if f.optional and not f.explicit_null else "encode"
            out.append(f"        try container.{method}(self.{ident(f.name)}, forKey: .{ident(f.name)})\n")
        if info.extras is not None:
            out.append(f"        try encoder.encodeExtras(self.extras, excluding: {known})\n")
        out.append("    }\n}\n")
        return "".join(out)

    def enum_source(self, name: str, schema: dict, description: str | None = None) -> str:
        values = schema["enum"]
        if not all(isinstance(v, str) for v in values) or schema.get("type", "string") != "string":
            raise UnsupportedSchema(f"{name}: only string enums are supported")
        taken = {"unknown", "rawValue", "allCases", "hashValue"}
        cases: list[tuple[str, str | None]] = []  # (wire, case name); None = carried by unknown(String)
        for value in values:
            base = lower_camel(value) if value else "empty"
            cases.append((value, None if base == "unknown" else unique(base, taken)))
        out = [doc(description), f"enum {name}: Codable, Hashable, Sendable, CaseIterable, RawRepresentable {{\n"]
        for _, case in cases:
            if case is not None:
                out.append(f"    case {ident(case)}\n")
        out.append("    /// A value this contract doesn't know, kept as sent.\n")
        out.append("    case unknown(String)\n\n")
        all_cases = ", ".join(f".{ident(c)}" if c is not None else f".unknown({swift_string(w)})" for w, c in cases)
        out.append(f"    static let allCases: [{name}] = [{all_cases}]\n\n")
        out.append("    init(rawValue: String) {\n        switch rawValue {\n")
        for wire, case in cases:
            if case is not None:
                out.append(f"        case {swift_string(wire)}: self = .{ident(case)}\n")
        out.append("        default: self = .unknown(rawValue)\n        }\n    }\n\n")
        out.append("    var rawValue: String {\n        switch self {\n")
        for wire, case in cases:
            if case is not None:
                out.append(f"        case .{ident(case)}: return {swift_string(wire)}\n")
        out.append("        case let .unknown(value): return value\n        }\n    }\n\n")
        out.append("    init(from decoder: Decoder) throws {\n"
                   "        self.init(rawValue: try decoder.singleValueContainer().decode(String.self))\n"
                   "    }\n\n"
                   "    func encode(to encoder: Encoder) throws {\n"
                   "        var container = encoder.singleValueContainer()\n"
                   "        try container.encode(rawValue)\n"
                   "    }\n}\n")
        return "".join(out)

    def choice_source(self, name: str, variants: list[SwiftType]) -> str:
        names = [t.label for t in variants]
        if len(set(names)) != len(names):
            raise UnsupportedSchema(f"{name}: two variants share a case name")
        out = [f"/// One of {', '.join(f'`{t.swift}`' for t in variants)}, tried in that order.\n",
               f"enum {name}: Codable, Hashable, Sendable {{\n"]
        for t in variants:
            out.append(f"    case {ident(t.label)}({t.swift})\n")
        out.append("\n    init(from decoder: Decoder) throws {\n"
                   "        let container = try decoder.singleValueContainer()\n")
        for t in variants:
            out.append(f"        if let value = try? container.decode({t.swift}.self) {{\n"
                       f"            self = .{ident(t.label)}(value)\n            return\n        }}\n")
        out.append(f"        throw DecodingError.dataCorruptedError(in: container, debugDescription: "
                   f"\"No variant of {name} matched\")\n    }}\n\n")
        out.append("    func encode(to encoder: Encoder) throws {\n"
                   "        var container = encoder.singleValueContainer()\n        switch self {\n")
        for t in variants:
            out.append(f"        case let .{ident(t.label)}(value): try container.encode(value)\n")
        out.append("        }\n    }\n}\n")
        return "".join(out)

    def union_source(self, name: str, prop: str, tags: list[tuple[str, str]]) -> str:
        taken = {"unknown", "hashValue"}
        cases = [(tag, unique(lower_camel(tag), taken), target) for tag, target in tags]
        targets = OrderedDict()
        for tag, _, target in cases:
            targets.setdefault(target, []).append(f"`{tag}`")
        summary = "; ".join(f"{', '.join(t)} -> `{target}`" for target, t in targets.items())
        out = [f"/// Tagged by `{prop}`: {summary}. The case decides the tag written.\n",
               f"enum {name}: Codable, Hashable, Sendable {{\n"]
        for _, case, target in cases:
            out.append(f"    case {ident(case)}({target})\n")
        out.append("    /// A tag this contract doesn't know, kept as sent.\n    case unknown(JSONValue)\n\n")
        out.append("    init(from decoder: Decoder) throws {\n"
                   "        let tag = try? decoder.container(keyedBy: AnyCodingKey.self)"
                   f".decode(String.self, forKey: AnyCodingKey({swift_string(prop)}))\n"
                   "        switch tag {\n")
        for tag, case, target in cases:
            out.append(f"        case {swift_string(tag)}?: self = .{ident(case)}(try {target}(from: decoder))\n")
        out.append("        default: self = .unknown(try JSONValue(from: decoder))\n        }\n    }\n\n")
        out.append("    func encode(to encoder: Encoder) throws {\n        switch self {\n")
        for tag, case, _ in cases:
            out.append(f"        case let .{ident(case)}(value):\n"
                       f"            try JSONValue.encode(value).setting({swift_string(prop)}, "
                       f"{swift_string(tag)}).encode(to: encoder)\n")
        out.append("        case let .unknown(raw):\n            try raw.encode(to: encoder)\n        }\n    }\n}\n")
        return "".join(out)

    # Calls ------------------------------------------------------------------------------------------

    def call_type(self, schema: dict | None, ctx: str) -> tuple[str, StructInfo | None]:
        if schema is None:
            return "JSONValue", None
        self.owner = ctx
        resolved, nullable = self.resolve(schema, ctx)
        struct = self.structs.get(resolved.name) if resolved.kind == "named" else None
        return resolved.swift + ("?" if nullable else ""), struct

    def methods_source(self) -> str:
        out = [HEADER, "\nimport Foundation\n\n",
               "/// Typed calls for every client→server method of the contract. Params are encoded with nil members\n"
               "/// omitted; a result that doesn't match its type throws `GatewayDecodingError` carrying the raw value.\n",
               "struct GatewayClient {\n    let transport: any GatewayCalling\n"]
        taken = {"transport", "request"}
        for m in self.contract.methods:
            ctx = upper_camel(m.name)
            params, params_struct = self.call_type(m.params, ctx + "Params")
            result, _ = self.call_type(m.result, ctx + "Result")
            default = " = .init()" if params_struct is not None and params_struct.zero_arg_init else ""
            fn = unique(lower_camel(m.name), taken)
            out.append("\n" + doc(m.summary, "    "))
            out.append(f"    func {ident(fn)}(_ params: {params}{default}, timeout: TimeInterval? = nil) "
                       f"async throws -> {result} {{\n")
            out.append(f"        try await request({swift_string(m.name)}, params, timeout)\n    }}\n")
        out.append(
            "\n    private func request<Params: Encodable, Response: Decodable>(\n"
            "        _ method: String, _ params: Params, _ timeout: TimeInterval?\n"
            "    ) async throws -> Response {\n"
            "        let raw = try await transport.call(method, params: JSONValue.encode(params), timeout: timeout)\n"
            "        do {\n            return try raw.decode(Response.self)\n        } catch {\n"
            "            throw GatewayDecodingError(method: method, raw: raw, underlying: error)\n        }\n    }\n}\n")
        return "".join(out)

    def events_source(self) -> str:
        taken = {"unknown", "type", "decode", "typed"}
        rows = []
        for e in self.contract.events:
            payload = None if self.is_empty_object(e.params) else self.call_type(e.params, upper_camel(e.name) + "Payload")[0]
            rows.append((e, unique(lower_camel(e.name), taken), payload))
        out = [HEADER, "\nimport Foundation\nimport os\n\n",
               'private let eventLog = Logger(subsystem: Bundle.main.bundleIdentifier ?? "HermesVoice", '
               'category: "GatewayEvent")\n\n',
               "/// A gateway notification: an `event` frame's `type` and `payload`, typed from the contract.\n"
               "/// Decoding never fails: an unknown type, or a payload that doesn't match (logged), is `.unknown`.\n",
               "enum GatewayEvent: Hashable, Sendable {\n"]
        for e, case, payload in rows:
            out.append(doc(e.summary, "    "))
            out.append(f"    case {ident(case)}" + (f"({payload})" if payload else "") + "\n")
        out.append("    case unknown(type: String, payload: JSONValue?)\n\n")
        out.append("    static func decode(type: String, payload: JSONValue?) -> GatewayEvent {\n        switch type {\n")
        for e, case, payload in rows:
            body = f"typed(type, payload, GatewayEvent.{ident(case)})" if payload else f".{ident(case)}"
            out.append(f"        case {swift_string(e.name)}: return {body}\n")
        out.append("        default: return .unknown(type: type, payload: payload)\n        }\n    }\n\n")
        out.append("    /// The wire `type`.\n    var type: String {\n        switch self {\n")
        for e, case, _ in rows:
            out.append(f"        case .{ident(case)}: return {swift_string(e.name)}\n")
        out.append("        case let .unknown(type, _): return type\n        }\n    }\n\n")
        out.append(
            "    private static func typed<Payload: Decodable>(\n"
            "        _ type: String, _ payload: JSONValue?, _ make: (Payload) -> GatewayEvent\n"
            "    ) -> GatewayEvent {\n"
            "        do {\n            return make(try (payload ?? [:]).decode(Payload.self))\n        } catch {\n"
            "            eventLog.error(\"Event \\(type, privacy: .public) doesn't match the contract: "
            "\\(String(describing: error), privacy: .public)\")\n"
            "            return .unknown(type: type, payload: payload)\n        }\n    }\n}\n")
        return "".join(out)

    def is_empty_object(self, schema: dict) -> bool:
        return schema.get("type") == "object" and not schema.get("properties") and schema.get(
            "additionalProperties") is False

    def server_requests_source(self) -> str:
        taken = {"unknown", "id", "method", "sessionID", "decode", "typed", "nonEmpty"}
        rows = []
        for r in self.contract.requests:
            params, struct = self.call_type(r.params, upper_camel(r.name) + "RequestParams")
            result, _ = self.call_type(r.result, upper_camel(r.name) + "RequestResult")
            rows.append((r, unique(lower_camel(r.name), taken), params, struct, result))
        out = [HEADER, "\nimport Foundation\nimport os\n\n",
               'private let requestLog = Logger(subsystem: Bundle.main.bundleIdentifier ?? "HermesVoice", '
               'category: "ServerRequest")\n\n',
               "/// A server→client request: Hermes calls the app and waits for the answer type named on each case.\n"
               "/// Decoding never fails: an unknown method, or params that don't match (logged), is `.unknown`.\n",
               "enum ServerRequest: Hashable, Sendable {\n"]
        for r, case, params, _, result in rows:
            out.append(doc(f"{r.summary} Answer: `{result}`.", "    "))
            out.append(f"    case {ident(case)}(id: String, params: {params})\n")
        out.append("    case unknown(id: String, method: String, params: JSONValue?)\n\n")
        out.append("    static func decode(id: String, method: String, params: JSONValue?) -> ServerRequest {\n"
                   "        switch method {\n")
        for r, case, params, _, _ in rows:
            out.append(f"        case {swift_string(r.name)}: return typed(id, method, params, {params}.self) "
                       f"{{ .{ident(case)}(id: id, params: $0) }}\n")
        out.append("        default: return .unknown(id: id, method: method, params: params)\n        }\n    }\n\n")
        out.append("    var id: String {\n        switch self {\n")
        for _, case, _, _, _ in rows:
            out.append(f"        case let .{ident(case)}(id, _): return id\n")
        out.append("        case let .unknown(id, _, _): return id\n        }\n    }\n\n")
        out.append("    var method: String {\n        switch self {\n")
        for r, case, _, _, _ in rows:
            out.append(f"        case .{ident(case)}: return {swift_string(r.name)}\n")
        out.append("        case let .unknown(_, method, _): return method\n        }\n    }\n\n")
        out.append("    /// The session the request belongs to; nil for app-level prompts (sent with an empty session).\n"
                   "    var sessionID: String? {\n        switch self {\n")
        for _, case, _, struct, _ in rows:
            expr = self.session_id_expr(struct)
            out.append(f"        case let .{ident(case)}(_, params): return "
                       + (f"nonEmpty({expr})" if expr != "nil" else "nil") + "\n")
        out.append('        case let .unknown(_, _, params): return nonEmpty(params?["session_id"]?.stringValue)\n'
                   "        }\n    }\n\n")
        out.append("    private func nonEmpty(_ id: String?) -> String? {\n"
                   "        id?.isEmpty == false ? id : nil\n    }\n\n")
        out.append(
            "    private static func typed<Params: Decodable>(\n"
            "        _ id: String, _ method: String, _ params: JSONValue?, _: Params.Type,\n"
            "        _ make: (Params) -> ServerRequest\n"
            "    ) -> ServerRequest {\n"
            "        do {\n            return make(try (params ?? [:]).decode(Params.self))\n        } catch {\n"
            "            requestLog.error(\"Request \\(method, privacy: .public) doesn't match the contract: "
            "\\(String(describing: error), privacy: .public)\")\n"
            "            return .unknown(id: id, method: method, params: params)\n        }\n    }\n}\n")
        return "".join(out)

    @staticmethod
    def session_id_expr(struct: StructInfo | None) -> str:
        if struct is not None:
            for f in struct.fields:
                if f.wire == "session_id" and f.type.swift == "String":
                    return f"params.{ident(f.name)}"
            if struct.extras is not None and struct.extras.swift == "JSONValue":
                return 'params.extras["session_id"]?.stringValue'
        return "nil"

    # Files ------------------------------------------------------------------------------------------

    def render(self) -> dict[str, str]:
        buckets: dict[str, list[str]] = OrderedDict((stem, []) for stem, _ in MODEL_BUCKETS)
        for name in sorted(self.contract.kept_schemas, key=lambda n: (n.lstrip("_").upper(), n)):
            first = name.lstrip("_")[:1].upper()
            stem = next((s for s, letters in MODEL_BUCKETS if first in letters), MODEL_BUCKETS[-1][0])
            buckets[stem].append(self.schema_source(name))
        files = OrderedDict()
        files["Methods.swift"] = self.methods_source()
        files["Events.swift"] = self.events_source()
        files["ServerRequests.swift"] = self.server_requests_source()
        for stem, sources in buckets.items():
            files[f"{stem}.swift"] = HEADER + "\nimport Foundation\n\n" + "\n".join(sources)
        synth = [self.synth[n] for n in sorted(self.synth)]
        files["Models.swift"] = HEADER + "\nimport Foundation\n\n" + "\n".join(synth)
        return OrderedDict(sorted((k, _tidy(v)) for k, v in files.items()))


def _tidy(text: str) -> str:
    return "\n".join(line.rstrip() for line in text.splitlines()).rstrip("\n") + "\n"


def render_contract(doc: dict) -> tuple[dict[str, str], Renderer]:
    renderer = Renderer(Contract(doc))
    return renderer.render(), renderer


def summary(renderer: Renderer) -> str:
    c = renderer.contract
    return (f"methods {len(c.methods)} (stripped {len(c.stripped_methods)}), "
            f"events {len(c.events)} (stripped {len(c.stripped_events)}), "
            f"server requests {len(c.requests)}, schemas {len(c.kept_schemas)} (stripped {len(c.stripped_schemas)}), "
            f"helper types {len(renderer.synth)}")


# ── Pinning ───────────────────────────────────────────────────────────────────────────────────────


def _git(hermes: Path, *args: str) -> str:
    try:
        out = subprocess.run(["git", "-C", str(hermes), *args], capture_output=True, text=True, check=True)
        return out.stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return ""


def hermes_provenance(hermes: Path) -> dict[str, str]:
    version = ""
    pyproject = hermes / "pyproject.toml"
    if pyproject.exists():
        match = re.search(r'^version\s*=\s*"([^"]+)"', pyproject.read_text(encoding="utf-8"), re.M)
        version = match.group(1) if match else ""
    return {
        "version": version or "unknown",
        "describe": _git(hermes, "describe", "--tags", "--always") or "unknown",
        "commit": _git(hermes, "rev-parse", "--short", "HEAD") or "unknown",
        "date": _git(hermes, "log", "-1", "--format=%cs") or "unknown",
    }


def readme_text(info: dict[str, str], digest: str) -> str:
    return (
        "# Gateway contract\n\n"
        "`gateway-contract.openrpc.json` is a pinned copy of Hermes' `apps/shared/src/gateway-contract.openrpc.json`:\n"
        "the OpenRPC description of the `/api/ws` JSON-RPC gateway (client→server methods, `x-server-requests`,\n"
        "`x-notifications`), generated in Hermes from `tui_gateway/contracts`.\n"
        "`HermesVoice/tools/gen_swift_gateway.py` renders it into `HermesVoice/HermesVoice/Gateway/Generated/`.\n\n"
        "| | |\n|---|---|\n"
        f"| hermes-agent version (pyproject) | `{info['version']}` |\n"
        f"| git describe | `{info['describe']}` |\n"
        f"| commit | `{info['commit']}` ({info['date']}) |\n"
        f"| SHA-256 | `{digest}` |\n\n"
        "Re-pin from a Hermes checkout (default `~/.hermes/hermes-agent`, or `--hermes DIR`) and regenerate:\n\n"
        "```sh\npython3 HermesVoice/tools/gen_swift_gateway.py --update\n```\n\n"
        "`--check` exits 1 when the generated Swift no longer matches this contract.\n"
    )


def update_contract(hermes: Path, contract: Path, readme: Path) -> None:
    source = hermes / HERMES_CONTRACT
    if not source.exists():
        raise SystemExit(f"no contract at {source}")
    json.loads(source.read_text(encoding="utf-8"))
    contract.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(source, contract)
    digest = hashlib.sha256(contract.read_bytes()).hexdigest()
    readme.write_text(readme_text(hermes_provenance(hermes), digest), encoding="utf-8")
    print(f"pinned contract from {hermes.name} ({digest[:12]})")


# ── CLI ───────────────────────────────────────────────────────────────────────────────────────────


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true", help="exit 1 if the generated Swift is stale")
    mode.add_argument("--update", action="store_true", help="copy the contract from Hermes first")
    parser.add_argument("--hermes", type=Path, default=Path(os.environ.get("HERMES_AGENT_DIR", DEFAULT_HERMES)),
                        help="Hermes checkout for --update (default ~/.hermes/hermes-agent or $HERMES_AGENT_DIR)")
    parser.add_argument("--contract", type=Path, default=CONTRACT, help=argparse.SUPPRESS)
    parser.add_argument("--out", type=Path, default=OUT_DIR, help=argparse.SUPPRESS)
    args = parser.parse_args(argv)

    if args.update:
        update_contract(args.hermes.expanduser(), args.contract, args.contract.parent / CONTRACT_README.name)
    files, renderer = render_contract(json.loads(args.contract.read_text(encoding="utf-8")))
    existing = {p.name for p in args.out.glob("*.swift")} if args.out.exists() else set()
    stale = sorted(n for n, text in files.items()
                   if not (args.out / n).exists() or (args.out / n).read_text(encoding="utf-8") != text)
    extra = sorted(existing - set(files))
    if args.check:
        for name in stale + extra:
            print(f"stale: {name} — run HermesVoice/tools/gen_swift_gateway.py", file=sys.stderr)
        return 1 if stale or extra else 0
    args.out.mkdir(parents=True, exist_ok=True)
    for name in stale:
        (args.out / name).write_text(files[name], encoding="utf-8")
        print(f"wrote {name}")
    for name in extra:
        (args.out / name).unlink()
        print(f"removed {name}")
    print(summary(renderer))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
